/** Colours Material 3 has no role for. */
@Immutable
data class ExtendedColors(
    val success: Color,
    val onSuccess: Color,
    val successContainer: Color,
    val onSuccessContainer: Color,
    /** The e16's "pairing mode" LED. */
    val pairingBlue: Color,
)

private val LightExtended = ExtendedColors(
    success = Color(0xFF1E6C3E), onSuccess = Color.White,
    successContainer = Color(0xFFB6F2C6), onSuccessContainer = Color(0xFF00210E),
    pairingBlue = Color(0xFF2F7BFF),
)
private val DarkExtended = ExtendedColors(
    success = Color(0xFF9AD5AA), onSuccess = Color(0xFF00391B),
    successContainer = Color(0xFF00522A), onSuccessContainer = Color(0xFFB6F2C6),
    pairingBlue = Color(0xFF6EA2FF),
)

val LocalExtendedColors = staticCompositionLocalOf { LightExtended }

private val AppTypography = Typography().let { base ->
    base.copy(
        headlineMedium = base.headlineMedium.copy(fontWeight = FontWeight.SemiBold, letterSpacing = (-0.2).sp),
        titleMedium = base.titleMedium.copy(fontWeight = FontWeight.SemiBold),
        labelLarge = base.labelLarge.copy(fontWeight = FontWeight.SemiBold),
    )
}

@Composable
fun EasyConnectTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colors: ColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        darkTheme -> DarkColors
        else -> LightColors
    }
    CompositionLocalProvider(LocalExtendedColors provides if (darkTheme) DarkExtended else LightExtended) {
        MaterialTheme(colorScheme = colors, typography = AppTypography, content = content)
    }
}

object AppTheme {
    val extended: ExtendedColors
        @Composable get() = LocalExtendedColors.current
}
